// Turns shared/styles.ts into what each client reads:
//   styleCss()                    the token blocks at the top of the web stylesheet (build.ts prepends them)
//   bun tools/styles.ts           writes the native copies: android/.../ui/Styles.kt, mac/Sources/Panel/Styles.swift,
//                                 and the three marks as PNGs for both apps (rendered with rsvg-convert)
// tests/styles.test.ts compares the committed native copies with nativeKotlin() and nativeSwift().
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { STYLES, THEME_KEYS, LIGHTS, tokens } from "../shared/styles";
import type { Light, Theme } from "../shared/types";

const ROOT = join(import.meta.dir, "../..");
export const KOTLIN_PATH = join(ROOT, "android/app/src/main/kotlin/dev/kaleve/monet/ui/Styles.kt");
export const SWIFT_PATH = join(ROOT, "mac/Sources/Panel/Styles.swift");

/* ---------- web ---------- */

const decl = (o: Record<string, string>) => Object.entries(o).map(([k, v]) => (k === "scheme" ? `color-scheme:${v}` : `--${k}:${v}`)).join(";");
const diff = (a: Record<string, string>, b: Record<string, string>) => Object.fromEntries(Object.entries(b).filter(([k, v]) => a[k] !== v));

/** Monet is the plain :root (a page without data-theme wears it); the others follow in source order, so their base
 *  rule (same specificity as Monet's light rules) wins over those, and their own light rules win over everything. */
export function styleCss(): string {
  const out: string[] = ["/* generated from shared/styles.ts by tools/styles.ts */"];
  for (const t of THEME_KEYS) {
    const sel = t === "monet" ? ":root" : `:root[data-theme=${t}]`, base = tokens(t, "mittag");
    out.push(`${sel}{${decl({ ...base, scheme: base.scheme ?? "light" })}}`);
    for (const l of LIGHTS) {
      if (l === "mittag") continue;
      const d = diff(base, tokens(t, l));
      if (Object.keys(d).length) out.push(`${sel}[data-light=${l}]{${decl(d)}}`);
    }
    const night = diff(base, tokens(t, "nacht"));
    out.push(`@media (prefers-color-scheme: dark){${sel}:not([data-light]){${decl(night)}}}`);
  }
  return out.join("\n") + "\n";
}

/* ---------- native ---------- */

/** "#RRGGBB" or "rgb(r g b / a)" as 0xAARRGGBB; anything else (gradients, fonts, shadows) is web only. */
export function argb(v: string): number | null {
  let m = /^#([0-9a-f]{6})$/i.exec(v);
  if (m) return (0xff000000 | parseInt(m[1], 16)) >>> 0;
  m = /^rgba?\(\s*(\d+)[\s,]+(\d+)[\s,]+(\d+)\s*(?:[/,]\s*([\d.]+%?))?\s*\)$/.exec(v);
  if (!m) return null;
  const a = m[4] === undefined ? 1 : m[4].endsWith("%") ? parseFloat(m[4]) / 100 : parseFloat(m[4]);
  return ((Math.round(a * 255) << 24) | (+m[1] << 16) | (+m[2] << 8) | +m[3]) >>> 0;
}
const camel = (k: string) => k.replace(/-(\w)/g, (_, c) => c.toUpperCase());
/** The colours a native app can use: every colour token outside the map, the union over all styles. A style without
 *  one (only Ernst has wood) gets Monet's in the same light, so every palette has every field. */
function nativeKeys(): string[] {
  const keys = new Set<string>();
  for (const t of THEME_KEYS) for (const [k, v] of Object.entries(tokens(t, "mittag"))) if (!k.startsWith("k-") && argb(v) !== null) keys.add(k);
  return [...keys];
}
function nativeColour(t: Theme, l: Light, k: string): number {
  return argb(tokens(t, l)[k] ?? "") ?? argb(tokens("monet", l)[k] ?? "") ?? argb(tokens(t, l).ink)!;
}
const hex = (n: number) => "0x" + n.toString(16).toUpperCase().padStart(8, "0");
const cap = (s: string) => s[0].toUpperCase() + s.slice(1);
const HEAD = "Generated by app/tools/styles.ts from app/shared/styles.ts. Do not edit: change shared/styles.ts and run `bun tools/styles.ts`.";

export function nativeKotlin(): string {
  const keys = nativeKeys();
  const L: string[] = [`// ${HEAD}`, "package dev.kaleve.monet.ui", "", "import androidx.compose.ui.graphics.Color", "import dev.kaleve.monet.R", "import dev.kaleve.monet.core.Light", ""];
  L.push("enum class Underline { Dabs, Rubbing, Sky }", "enum class CardShape { Pebble, Engraving, Frame }", "enum class SunMark { Dot, Ring, Apple }", "");
  L.push("/** The colours of one style in one light. */");
  L.push(`data class Palette(\n${keys.map(k => `    val ${camel(k)}: Color,`).join("\n")}\n    val dark: Boolean,\n)`, "");
  L.push("/** Everything a client needs to wear a style. [mark] is the style's sign, rendered from the web SVG. */");
  L.push("class Style(\n    val key: String, val brand: String,\n    val underline: Underline, val card: CardShape, val sun: SunMark,\n    val italic: Boolean, val tracking: Float, val mark: Int,\n    private val palettes: Map<Light, Palette>,\n) {\n    fun palette(l: Light): Palette = palettes.getValue(l)\n}", "");
  L.push("object Styles {");
  for (const t of THEME_KEYS) {
    const s = STYLES[t], tq = s.technique;
    L.push(`    val ${t} = Style("${t}", "${s.brand}", Underline.${cap(tq.underline)}, CardShape.${cap(tq.card)}, SunMark.${cap(tq.sun)}, ${s.type.headings === "italic"}, ${s.type.tracking}f, R.drawable.mark_${t}, mapOf(`);
    for (const l of LIGHTS) L.push(`        Light.${cap(l)} to Palette(${keys.map(k => `Color(${hex(nativeColour(t, l, k))})`).join(", ")}, ${tokens(t, l).scheme === "dark"}),`);
    L.push("    ))");
  }
  L.push(`    val all = listOf(${THEME_KEYS.join(", ")})`);
  L.push("    /** The style of that name; Monet for anything unknown, so an older or newer server never breaks the app. */");
  L.push("    fun of(key: String?): Style = all.firstOrNull { it.key == key } ?: monet");
  L.push("}", "");
  return L.join("\n");
}

export function nativeSwift(): string {
  const keys = nativeKeys();
  const L: string[] = [`// ${HEAD}`, "import SwiftUI", ""];
  L.push("enum Underline { case dabs, rubbing, sky }", "enum CardShape { case pebble, engraving, frame }", "enum SunMark { case dot, ring, apple }", "");
  L.push("/// The colours of one style in one light.");
  L.push(`struct Palette: Equatable {\n    var ${keys.map(camel).join(", ")}: Color\n    var dark: Bool\n}`, "");
  L.push("/// Everything a client needs to wear a style. `mark` names the PNG in Contents/Resources, rendered from the web SVG.");
  L.push("struct Style: Equatable {\n    let key: String, brand: String\n    let underline: Underline, card: CardShape, sun: SunMark\n    let italic: Bool, tracking: CGFloat\n    /// font families to try in order for headings\n    let fonts: [String]\n    let mark: String\n    let palettes: [Light: Palette]\n    func palette(_ l: Light) -> Palette { palettes[l]! }\n}", "");
  L.push("private func rgba(_ v: UInt32) -> Color {");
  L.push("    Color(.sRGB, red: Double((v >> 16) & 255) / 255, green: Double((v >> 8) & 255) / 255, blue: Double(v & 255) / 255, opacity: Double((v >> 24) & 255) / 255)");
  L.push("}", "", "enum Styles {");
  for (const t of THEME_KEYS) {
    const s = STYLES[t], tq = s.technique;
    L.push(`    static let ${t} = Style(key: "${t}", brand: "${s.brand}", underline: .${tq.underline}, card: .${tq.card}, sun: .${tq.sun}, italic: ${s.type.headings === "italic"}, tracking: ${s.type.tracking}, fonts: ${JSON.stringify(s.type.native)}, mark: "mark-${t}", palettes: [`);
    for (const l of LIGHTS) L.push(`        .${l}: Palette(${keys.map(k => `${camel(k)}: rgba(${hex(nativeColour(t, l, k))})`).join(", ")}, dark: ${tokens(t, l).scheme === "dark"}),`);
    L.push("    ])");
  }
  L.push(`    static let all = [${THEME_KEYS.join(", ")}]`);
  L.push("    /// The style of that name; Monet for anything unknown, so an older or newer server never breaks the app.");
  L.push("    static func of(_ key: String?) -> Style { all.first { $0.key == key } ?? monet }");
  L.push("}", "");
  return L.join("\n");
}

if (import.meta.main) {
  writeFileSync(KOTLIN_PATH, nativeKotlin());
  writeFileSync(SWIFT_PATH, nativeSwift());
  const icons = join(import.meta.dir, "../client/icons"), drawable = join(ROOT, "android/app/src/main/res/drawable-nodpi"), res = join(ROOT, "mac/Resources");
  mkdirSync(drawable, { recursive: true }); mkdirSync(res, { recursive: true });
  for (const t of THEME_KEYS) {
    // 144 px: the 48 dp header mark at 3x on a phone, the 34 pt panel mark at 4x on the Mac
    for (const out of [join(drawable, `mark_${t}.png`), join(res, `mark-${t}.png`)]) {
      const r = Bun.spawnSync(["rsvg-convert", "-w", "144", "-h", "144", "-o", out, join(icons, STYLES[t].mark.file)]);
      if (r.exitCode !== 0) throw new Error(`rsvg-convert ${t}: ${r.stderr}`);
    }
  }
  console.log("wrote", KOTLIN_PATH, SWIFT_PATH, "and the marks");
}
